import com.plot.api.geometry.Vec2d;
import com.plot.plugin.config.RoadSystemConfig;
import com.plot.plugin.road.model.*;
import com.plot.plugin.road.station.RoadStationing;
import com.plot.plugin.road.pipeline.CrossSectionBuildContext;
import java.util.List;

RoadNetwork network = new RoadNetwork();
Road road = network.createRoad("main");
RoadNode a = network.createNode(new Vec2d(0, 0));
RoadNode b = network.createNode(new Vec2d(24, 0));
RoadNode c = network.createNode(new Vec2d(24, 24));
RoadNode d = network.createNode(new Vec2d(0, 24));
var e0 = network.createEdge(a.getId(), b.getId(), List.of(new Vec2d(0, 0), new Vec2d(24, 0)), road.getId());
network.createEdge(b.getId(), c.getId(), List.of(new Vec2d(24, 0), new Vec2d(24, 24)), road.getId());
network.createEdge(c.getId(), d.getId(), List.of(new Vec2d(24, 24), new Vec2d(0, 24)), road.getId());
network.createEdge(d.getId(), a.getId(), List.of(new Vec2d(0, 24), new Vec2d(0, 0)), road.getId());
System.out.println("stationable="+RoadStationing.isStationable(network, road));
System.out.println("ordered="+road.getOrderedSegmentIds());
System.out.println("topo="+road.getTopologyMode());
var config = new RoadSystemConfig("test");
var ctx = CrossSectionBuildContext.forEdge(network, e0, config);
System.out.println("orients="+ctx.lightingOrientations().size());
System.out.println("chain@12="+ctx.chainageAtGeometryLocal(12));
System.out.println("variable="+ctx.isVariable());
